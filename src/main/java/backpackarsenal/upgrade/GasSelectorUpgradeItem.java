package backpackarsenal.upgrade;

import net.minecraft.ChatFormatting;
import net.minecraft.network.chat.Component;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.TooltipFlag;
import net.minecraft.world.level.Level;
import net.p3pp3rf1y.sophisticatedbackpacks.Config;
import net.p3pp3rf1y.sophisticatedcore.api.IStorageWrapper;
import net.p3pp3rf1y.sophisticatedcore.upgrades.UpgradeItemBase;
import net.p3pp3rf1y.sophisticatedcore.upgrades.UpgradeType;
import net.p3pp3rf1y.sophisticatedcore.upgrades.UpgradeWrapperBase;
import org.jetbrains.annotations.Nullable;

import java.util.List;
import java.util.function.Consumer;

/** Upgrade-slot selector for the gas generated by a Fire backpack. */
public class GasSelectorUpgradeItem extends UpgradeItemBase<GasSelectorUpgradeItem.Wrapper> {
    public enum Mode { ETHENE, HYDROGEN_CHLORIDE }
    public static final UpgradeType<Wrapper> TYPE = new UpgradeType<>(Wrapper::new);
    private final Mode mode;

    public GasSelectorUpgradeItem(Mode mode) {
        super(Config.SERVER.maxUpgradesPerStorage);
        this.mode = mode;
    }

    public Mode getMode() { return mode; }
    @Override public UpgradeType<Wrapper> getType() { return TYPE; }
    @Override public List<UpgradeConflictDefinition> getUpgradeConflicts() { return List.of(); }

    @Override
    public void appendHoverText(ItemStack stack, @Nullable Level level,
                                List<Component> tooltip, TooltipFlag flag) {
        super.appendHoverText(stack, level, tooltip, flag);
        tooltip.add(Component.translatable("item.backpack_arsenal.gas_selector.tooltip")
            .withStyle(ChatFormatting.GRAY));
    }

    public static class Wrapper extends UpgradeWrapperBase<Wrapper, GasSelectorUpgradeItem> {
        public Wrapper(IStorageWrapper storage, ItemStack upgrade, Consumer<ItemStack> save) {
            super(storage, upgrade, save);
        }
        public Mode getMode() { return upgradeItem.getMode(); }
    }
}
